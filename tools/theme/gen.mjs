import fs from "fs";
import { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors } from "@material/material-color-utilities";
const out = new URL("../../app/static", import.meta.url).pathname;
fs.mkdirSync(out + "/fonts", { recursive: true });

// ---- color schemes ----
const seeds = { ocean: "#1E88E5", violet: "#6750A4", teal: "#00897B", sage: "#7C9A3D", desert: "#D9772B" };
const roles = ["primary","onPrimary","primaryContainer","onPrimaryContainer","secondary","onSecondary","secondaryContainer",
  "onSecondaryContainer","tertiary","onTertiary","tertiaryContainer","onTertiaryContainer","error","onError","errorContainer",
  "onErrorContainer","surface","onSurface","surfaceVariant","onSurfaceVariant","surfaceDim","surfaceBright",
  "surfaceContainerLowest","surfaceContainerLow","surfaceContainer","surfaceContainerHigh","surfaceContainerHighest",
  "outline","outlineVariant","inverseSurface","inverseOnSurface","inversePrimary","scrim","shadow"];
const kebab = s => s.replace(/[A-Z]/g, m => "-" + m.toLowerCase());
let css = "/* Generated by material-color-utilities (SchemeTonalSpot). Do not edit by hand. */\n";
for (const [name, hex] of Object.entries(seeds)) {
  for (const dark of [false, true]) {
    const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), dark, 0);
    const sel = `[data-seed="${name}"][data-mode="${dark ? "dark" : "light"}"]`;
    css += `${sel}{color-scheme:${dark ? "dark" : "light"};` +
      roles.map(r => `--md-${kebab(r)}:${hexFromArgb(MaterialDynamicColors[r].getArgb(s))}`).join(";") + "}\n";
  }
}
// semantic "warning" (amber) and "success" (green) palettes via the same machinery
for (const [k, hex] of Object.entries({ warn: "#F2A900", ok: "#2E9E44" })) {
  for (const dark of [false, true]) {
    const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), dark, 0);
    css += `[data-mode="${dark ? "dark" : "light"}"]{--md-${k}:${hexFromArgb(MaterialDynamicColors.primary.getArgb(s))};` +
      `--md-${k}-container:${hexFromArgb(MaterialDynamicColors.primaryContainer.getArgb(s))};` +
      `--md-on-${k}-container:${hexFromArgb(MaterialDynamicColors.onPrimaryContainer.getArgb(s))}}\n`;
  }
}
css += ":root{" + Object.entries(seeds).map(([n, h]) => `--seed-${n}:${h}`).join(";") + "}\n";
fs.writeFileSync(out + "/theme.css", css);

// ---- fonts ----
for (const w of [400, 500, 700])
  fs.copyFileSync(`node_modules/@fontsource/roboto/files/roboto-latin-${w}-normal.woff2`, `${out}/fonts/roboto-${w}.woff2`);

